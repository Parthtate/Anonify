"""Export the trained TF-IDF + LogisticRegression for TypeScript inference.

Run after train_model.py:  python ml/export_model.py
Writes src/lib/moderation-model.ts. A .ts module (rather than JSON) imports
identically under webpack and plain Node, with no import attributes.
Stop words need no export: they were dropped at fit time, so they are absent
from the vocabulary and an out-of-vocabulary token contributes nothing anyway.
"""
import os

import joblib

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(BASE_DIR, '..', 'src', 'lib', 'moderation-model.ts'))

vectorizer = joblib.load(os.path.join(BASE_DIR, 'vectorizer.pkl'))
model = joblib.load(os.path.join(BASE_DIR, 'offensive_language_model.pkl'))

assert vectorizer.norm == 'l2' and not vectorizer.sublinear_tf and not vectorizer.binary
assert vectorizer.ngram_range == (1, 1) and vectorizer.lowercase
assert list(model.classes_) == [0, 1]

# Order terms by column index so idf and coef line up positionally.
terms = sorted(vectorizer.vocabulary_, key=vectorizer.vocabulary_.get)
assert not any(' ' in t or ',' in t for t in terms), 'term would break the packed encoding'

# Every term is kept even at coef 0: it still contributes to the L2 norm.
idf = ','.join(f'{v:.6f}' for v in vectorizer.idf_)
coef = ','.join(f'{v:.6f}' for v in model.coef_[0])

source = f'''// Generated by ml/export_model.py — do not edit by hand.
// Packed as strings so the module stays small and type-checks instantly.
export const intercept = {model.intercept_[0]:.8f};
export const terms = '{' '.join(terms)}'.split(' ');
export const idf = '{idf}'.split(',').map(Number);
export const coef = '{coef}'.split(',').map(Number);
'''

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(source)

print(f'wrote {OUT}  ({len(terms)} terms, {os.path.getsize(OUT) / 1024:.0f} KB)')
